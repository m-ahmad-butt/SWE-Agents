from app.codegen.writer import list_project_files, write_code_file
from app.models.project import Project

# README.md file generator
def _detect_layout(files: list[str]) -> tuple[bool, bool, str, str]:
    has_backend = any(f.startswith("backend/") for f in files)
    has_frontend = any(f.startswith("frontend/") for f in files)
    backend_entry = "backend/main.py" if "backend/main.py" in files else "main.py"
    frontend_entry = "frontend/package.json" if "frontend/package.json" in files else ""
    return has_backend, has_frontend, backend_entry, frontend_entry


def generate_run_guide(project: Project) -> str:
    """Generate README.md with setup and run instructions for the generated project."""
    files = list_project_files(project.id)
    title = project.title or "Generated Application"
    has_backend, has_frontend, backend_entry, _ = _detect_layout(files)

    tech_lines: list[str] = []
    if project.srs and project.srs.technology_stack:
        tech_lines = [f"- {t}" for t in project.srs.technology_stack]
    elif has_backend and has_frontend:
        tech_lines = ["- Python / FastAPI (backend)", "- React (frontend)"]
    elif has_backend:
        tech_lines = ["- Python / FastAPI"]
    elif has_frontend:
        tech_lines = ["- React"]

    lines = [
        f"# {title}",
        "",
        "This application was generated by **AI Software Company**.",
        "Follow the steps below to install dependencies and run the project locally.",
        "",
    ]

    if tech_lines:
        lines.extend(["## Technology Stack", ""] + tech_lines + [""])

    lines.extend(["## Prerequisites", ""])
    prereqs = ["- Python 3.11 or newer"]
    if has_frontend:
        prereqs.append("- Node.js 18 or newer and npm")
    lines.extend(prereqs + ["", "## Project Structure", ""])
    if has_backend:
        lines.append("- `backend/` — API server")
    if has_frontend:
        lines.append("- `frontend/` — web UI")
    lines.append("- `README.md` — this file")
    lines.append("")

    if has_backend:
        backend_dir = "backend" if backend_entry.startswith("backend/") else "."
        module = backend_entry.replace("/", ".").removesuffix(".py")
        if module.endswith(".main"):
            module = module[:-5] + "main"
        uvicorn_target = module if module != "main" else "main:app"
        if backend_dir == "backend":
            uvicorn_target = "main:app"

        lines.extend(
            [
                "## Backend Setup",
                "",
                "```bash",
                f"cd {backend_dir}",
                "python -m venv .venv",
                "# Windows",
                r".venv\Scripts\activate",
                "# macOS / Linux",
                "source .venv/bin/activate",
                "pip install fastapi uvicorn pydantic",
                f"uvicorn {uvicorn_target} --reload --port 8000",
                "```",
                "",
                "The API will be available at **http://localhost:8000**.",
                "",
            ]
        )

    if has_frontend:
        lines.extend(
            [
                "## Frontend Setup",
                "",
                "Open a **second terminal** (keep the backend running if applicable):",
                "",
                "```bash",
                "cd frontend",
                "npm install",
                "npm run dev",
                "```",
                "",
                "The app will open at **http://localhost:5173** (or the port shown in the terminal).",
                "",
            ]
        )

    lines.extend(
        [
            "## Quick Start Checklist",
            "",
            "1. Download the project **ZIP** from AI Software Company.",
            "2. Unzip the archive to a folder on your machine.",
            "3. Open this **README.md** and follow the setup steps above.",
            "4. Start the backend (if present), then the frontend.",
            "5. Open the app URL in your browser.",
            "",
            "## Troubleshooting",
            "",
            "- **Port already in use** — change the port in the uvicorn or Vite command.",
            "- **Module not found** — ensure your virtual environment is activated and dependencies are installed.",
            "- **CORS errors** — confirm the backend is running before starting the frontend.",
            "",
            "## Documentation",
            "",
            "See the SRS PDF export in AI Software Company for full requirements and milestone documentation.",
            "",
        ]
    )

    return "\n".join(lines)


def save_run_guide(project: Project) -> str:
    """Write README.md into the generated project folder and return its content."""
    content = generate_run_guide(project)
    write_code_file(project.id, "README.md", content)
    return content
